"""
Shared helpers for the AML Shield Tier-A pipeline.

Keeps paths, column names and IO in one place so every stage reads/writes
consistently. Deliberately dependency-light (pandas/numpy only here).
"""
from __future__ import annotations
import os
import pandas as pd

# --- paths -------------------------------------------------------------------
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RAW_CSV = os.path.join(ROOT, "data", "mule_sample_data.csv")
# synthetic scenario dataset (jury-approved) — labeled, with real timestamps and
# counterparty edges. Generated by ml_pipeline/synth/generate.py. Kept SEPARATE
# from the real file so the real Tier-A path is never contaminated.
SYN_CSV = os.path.join(ROOT, "data", "synthetic_scenario.csv")
SYN_ACCOUNTS = os.path.join(ROOT, "data", "synthetic_accounts.csv")
# Output dir is overridable so a caller can sandbox a run (the ml_viz visualizer
# gives every run its own temp dir). Unset -> the normal ml_pipeline/output, so
# run_all.sh / run_synthetic.sh behave exactly as before.
OUT = os.environ.get("AML_PIPELINE_OUT") or os.path.join(HERE, "output")
os.makedirs(OUT, exist_ok=True)

# raw file is pipe-delimited; the synthetic file is standard CSV.
SEP = "|"
SYN_SEP = ","

# provenance tags
SOURCE_REAL = "real"
SOURCE_SYNTHETIC = "synthetic"

# reference "now" for tenure/dormancy maths. The single TRAN_DATE in the file
# is 19/05/2026 18:30, so we anchor tenure to that transaction date.
REF_DATE = pd.Timestamp("2026-05-19 18:30:00")

# IOB-specific rule "standalone risk caps": if this single typology fires at
# full severity, how risky is the account on its own (0-1)? We combine rules
# with a noisy-OR so ONE strong typology already produces a high score and
# additional typologies compound it (never exceeding 100). This is more
# defensible than additive points, which either under-count a single clear
# signal or over-count when several fire.
RULE_CAPS = {
    "pass_through": 0.75,        # money in ~ money out, little retained (conduit)
    "fan_in_aggregation": 0.70,  # many incoming credits vs few pay-outs (collector)
    "structuring": 0.70,         # txns clustered just under the Rs 50k CTR line
    "new_account_burst": 0.45,   # young account, unusually high activity
    "micro_credit_flood": 0.40,  # flood of tiny credits (UPI smurfing signature)
    "high_lien_ratio": 0.25,     # large lien vs turnover (funds parked/frozen)
}

# fusion weights: rule score anchors because N=19 makes the ML term unstable.
W_RULE = 0.65
W_ANOM = 0.35

# alert threshold on the 0-100 composite (locked decision: fixed cutoff)
FLAG_THRESHOLD = 60.0


def load_raw() -> pd.DataFrame:
    """Load the raw Finacle-style transaction extract (REAL data, real-only).

    Deliberately unchanged: the backend and the Tier-A pipeline both depend on
    this returning exactly the 19-account sample. Synthetic data never flows
    through here — use load_synthetic() / load().
    """
    df = pd.read_csv(RAW_CSV, sep=SEP, dtype=str)
    # numeric coercions
    for c in ["TRAN_AMT", "balance", "LIEN_AMT", "customer_age"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    # dates (dd/mm/YYYY HH:MM)
    for c in ["TRAN_DATE", "ACCT_OPN_DATE"]:
        df[c] = pd.to_datetime(df[c], format="%d/%m/%Y %H:%M", errors="coerce")
    return df


def load_synthetic() -> pd.DataFrame:
    """Load the labeled synthetic scenario dataset.

    Same base schema as the real extract PLUS `BENEFICIARY_ACID` (counterparty
    edge) and `is_mule` (account-level ground-truth label). Unlike the real file,
    `TRAN_DATE` carries a genuine time spread, so temporal + graph features become
    computable here.
    """
    if not os.path.exists(SYN_CSV):
        raise FileNotFoundError(
            f"{SYN_CSV} not found — generate it first: python ml_pipeline/synth/generate.py"
        )
    df = pd.read_csv(SYN_CSV, sep=SYN_SEP, dtype=str)
    for c in ["TRAN_AMT", "balance", "LIEN_AMT", "customer_age", "is_mule"]:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    for c in ["TRAN_DATE", "ACCT_OPN_DATE"]:
        df[c] = pd.to_datetime(df[c], errors="coerce")
    df["source"] = SOURCE_SYNTHETIC
    return df


def load(source: str = SOURCE_REAL) -> pd.DataFrame:
    """Provenance-aware loader. source ∈ {real, synthetic, both}.

    `both` concatenates the two (each row keeps its `source` tag). Columns absent
    in one source (e.g. BENEFICIARY_ACID/is_mule for real) become NaN there, which
    the feature stage treats as "not available" rather than fabricating values.
    """
    if source == SOURCE_REAL:
        return load_raw()
    if source == SOURCE_SYNTHETIC:
        return load_synthetic()
    if source == "both":
        real = load_raw()
        real["source"] = SOURCE_REAL
        return pd.concat([real, load_synthetic()], ignore_index=True)
    raise ValueError(f"unknown source {source!r} (expected real|synthetic|both)")


def has_time_axis(df: pd.DataFrame) -> bool:
    """True when TRAN_DATE carries a real spread (temporal features computable)."""
    return "TRAN_DATE" in df.columns and df["TRAN_DATE"].nunique(dropna=True) > 1


def has_counterparty(df: pd.DataFrame) -> bool:
    """True when account→account edges exist (graph features computable)."""
    return "BENEFICIARY_ACID" in df.columns and df["BENEFICIARY_ACID"].notna().any()


def short(acid: str, n: int = 6) -> str:
    """Short, human-readable account id for reports."""
    return str(acid)[:n]
