import { useState, useEffect } from 'react';
import { api } from '@/lib/api.js';
import { Button } from '@/components/ui/button';

export default function STRDraftPanel({ caseId, confidence, strStatus, setStrStatus, onCiteHighlight, openDrawer }) {
  const [draft, setDraft] = useState(null);
  const [job, setJob] = useState(null);          // live generation job (real steps)
  const [phase, setPhase] = useState('empty');   // empty | generating | ready
  const [chips, setChips] = useState([]);
  const [citedSegment, setCitedSegment] = useState(null);
  const [error, setError] = useState(null);

  // load an existing draft if this case already has one
  useEffect(() => {
    let cancelled = false;
    if (strStatus && strStatus !== 'none') {
      api.strGet(caseId).then((d) => {
        if (!cancelled && d) { setDraft(d); setChips(d.evidenceChips || []); setPhase('ready'); }
      }).catch(() => {});
    } else {
      setPhase('empty'); setDraft(null);
    }
    return () => { cancelled = true; };
  }, [caseId, strStatus]);

  const applyDraft = (d) => {
    if (!d) return false;
    setDraft(d); setChips(d.evidenceChips || []); setPhase('ready'); setStrStatus('drafting');
    return true;
  };

  const pollJob = async (jobId) => {
    // Generation ends on the last step with a live OpenAI call, so it can take a
    // while. Poll generously, and if it ever stalls fall back to fetching the
    // draft directly rather than leaving the spinner stuck forever.
    for (let i = 0; i < 90; i++) {
      const j = await api.strJob(caseId, jobId);
      setJob(j);
      if (j.status === 'completed') { applyDraft(j.draft || await api.strGet(caseId)); return; }
      if (j.status === 'failed') { setError('Generation failed — please try again.'); setPhase('empty'); return; }
      await new Promise((r) => setTimeout(r, 400));
    }
    // Timed out waiting on the job — the backend may still have persisted a draft.
    if (!applyDraft(await api.strGet(caseId).catch(() => null))) {
      setError('Generation timed out — please try again.');
      setPhase('empty');
    }
  };

  const handleGenerate = async () => {
    setError(null);
    setPhase('generating');
    try {
      const j = await api.strGenerate(caseId, confidence ?? 87);
      setJob(j);
      await pollJob(j.job_id);
    } catch { setError('Could not reach the backend.'); setPhase('empty'); }
  };

  const handleCite = (seg) => {
    setCitedSegment(seg.chipId);
    onCiteHighlight(seg.highlight);
    setTimeout(() => { setCitedSegment(null); onCiteHighlight(null); }, 2200);
  };
  const toggleChip = (id) => setChips(chips.map((c) => (c.id === id ? { ...c, checked: !c.checked } : c)));
  const submitReview = async () => { try { await api.strSubmitReview(caseId); setStrStatus('review'); } catch { /* ignore */ } };

  if (phase === 'empty') {
    return (
      <div className="str-draft-content">
        <div className="str-empty">
          <div className="str-empty-icon">⊙</div>
          <h4>STR Draft not started</h4>
          <p>Generate an AI-assisted Suspicious Transaction Report pre-populated with case evidence, risk signals, and entity details.</p>
          {error && <div style={{fontSize:11,color:"var(--red)",maxWidth:240}}>{error}</div>}
          <Button variant="purple" size="lg" className="px-[18px] text-xs" onClick={handleGenerate}>{error ? "↻ Retry Draft" : "⊕ Generate STR Draft"}</Button>
          <div style={{fontSize:10,color:"var(--muted)",maxWidth:240,lineHeight:1.6}}>
            Draft is generated by the backend (OpenAI when configured) — narrative, triggered rules, entity table, and compliance checklist.
          </div>
        </div>
      </div>
    );
  }

  if (phase === 'generating') {
    const steps = job?.steps || [];
    return (
      <div className="str-draft-content">
        <div className="str-generating">
          <div className="str-gen-spinner"></div>
          <div style={{fontSize:12,color:"var(--text)",fontWeight:500}}>Generating STR Draft…</div>
          <div className="str-gen-steps">
            {steps.map((s) => (
              <div key={s.index} className={`str-gen-step ${s.status === 'done' ? 'done' : s.status === 'running' ? 'running' : ''}`}>
                <span className="gstep-dot"></span>
                <span>{s.label}</span>
              </div>
            ))}
          </div>
        </div>
      </div>
    );
  }

  if (!draft) return null;
  const cite = (draft.citeSegments || []).slice(0, 3);
  const previewText = (draft.narrative || '').slice(0, 320) + '…';
  const entities = draft.entities || [];
  const compliance = draft.complianceItems || [];

  return (
    <div className="str-draft-content">
      <div className="str-draft-scroll scroll">
        <div className="cite-graph-banner">
          <span className="cg-icon">⟳</span>
          <span>Hover highlighted text to cite evidence to the graph</span>
        </div>

        <div className="str-section">
          <div className="str-section-head">
            <div className="str-section-title">Narrative Preview</div>
            <span className="str-section-action" onClick={openDrawer}>Open full editor →</span>
          </div>
          <div style={{background:"var(--bg)",border:"1px solid var(--border-strong)",borderRadius:3,padding:"10px 12px",fontSize:11,lineHeight:1.7,color:"var(--text-dim)"}}>
            {cite.length === 0 ? previewText : cite.reduce((parts, seg, idx) => {
              const before = idx === 0 ? previewText.split(seg.text)[0] : parts[parts.length-1];
              const after = previewText.split(seg.text)[1] || "";
              if (previewText.includes(seg.text)) {
                parts[parts.length-1] = before;
                parts.push(
                  <span key={idx} className={`str-cite ${citedSegment===seg.chipId?"graph-lit":""}`}
                    onMouseEnter={() => handleCite(seg)} title="Click to cite in graph">
                    {seg.text}
                  </span>
                );
                parts.push(after);
              }
              return parts;
            }, [previewText])}
          </div>
        </div>

        <div className="str-section">
          <div className="str-section-head"><div className="str-section-title">Triggered Rules</div></div>
          <div className="evidence-chips">
            {chips.map((chip) => (
              <div key={chip.id} className={`evidence-chip ${chip.cls}`} style={{opacity:chip.checked?1:0.4}} onClick={() => toggleChip(chip.id)}>
                <span className="chip-check">{chip.checked?"☑":"☐"}</span>
                {chip.label}
              </div>
            ))}
          </div>
        </div>

        <div className="str-section">
          <div className="str-section-head"><div className="str-section-title">Reported Entities</div></div>
          <table className="str-entity-table">
            <thead><tr><th>Account</th><th>Role</th><th>Amount</th></tr></thead>
            <tbody>
              {entities.map((e, i) => (
                <tr key={i}><td className="hl">{e.account}</td><td>{e.role}</td><td className="warn-c">{e.amount}</td></tr>
              ))}
            </tbody>
          </table>
        </div>

        <div className="str-section">
          <div className="str-section-head"><div className="str-section-title">Filing Checklist</div></div>
          <div className="compliance-list">
            {compliance.map((item, i) => (
              <div key={i} className={`compliance-item ${item.status}`}>
                <span className="ci-icon" style={{color:item.status==="ok"?"var(--green)":item.status==="warn"?"var(--amber)":"var(--red)"}}>{item.icon}</span>
                <span className="ci-label">{item.label}</span>
                <span className="ci-status">{item.status === "ok" ? "Pass" : item.status === "warn" ? "Review" : "Note"}</span>
              </div>
            ))}
          </div>
        </div>
      </div>

      <div className="str-footer">
        <span className="str-save-status"><span className="str-save-dot"></span>Draft saved</span>
        <span className="str-word-count">{(draft.narrative || '').split(/\s+/).filter(Boolean).length} words</span>
        <Button variant="sky" size="sm" onClick={openDrawer}>⤢ Expand</Button>
        <Button variant="purple" size="sm" onClick={submitReview}>↑ Submit for Review</Button>
      </div>
    </div>
  );
}
